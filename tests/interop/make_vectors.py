#!/usr/bin/env python3
"""Generate tests/crypto_vectors.h from the Python version's own code.

Imports CryptoManager from the original cryptara.py (path given on the
command line) and records what it produces: key derivations, a message
encrypted with a password, a Diffie-Hellman exchange with known private
keys, a message encrypted with the resulting session key, and the public
key encoding.  test_crypto.cpp checks the C++ implementation against them.

    python3 make_vectors.py /path/to/cryptara.py > ../crypto_vectors.h

Needs PyQt6 and cryptography (cryptara.py imports both).
"""
import base64
import importlib.util
import os
import sys

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")


def load_cryptara(path):
    spec = importlib.util.spec_from_file_location("cryptara_original", path)
    module = importlib.util.module_from_spec(spec)
    # The module prints debug lines; keep them off our stdout.
    real_stdout = sys.stdout
    sys.stdout = sys.stderr
    try:
        spec.loader.exec_module(module)
    finally:
        sys.stdout = real_stdout
    return module


def c_string(data: bytes) -> str:
    return '"' + "".join("\\x%02x" % b for b in data) + '"'


def c_text(text: str) -> str:
    return c_string(text.encode("utf-8"))


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    cryptara = load_cryptara(sys.argv[1])
    quiet = sys.stdout
    sys.stdout = sys.stderr  # CryptoManager prints [DEBUG] lines

    out = []
    emit = out.append

    password = "  correct horse battery 73  "   # surrounding blanks are stripped
    message = "Bonjour de la station, 73 ! éèà \U0001F512 <tag> | pipes"

    a = cryptara.CryptoManager()
    a.set_password(password)
    a.enable()

    salt = bytes(range(16))
    k_enc = a.derive_key(a.master_password, salt, b"encryption")
    k_mac = a.derive_key(a.master_password, salt, b"hmac")
    password_msg = a.encrypt(message)

    # Diffie-Hellman between two Python stations.
    a.generate_dh_keypair()
    b = cryptara.CryptoManager()
    b.set_password(password)
    b.enable()
    b.generate_dh_keypair()
    a_pub = a.serialize_public_key(a.dh_public_key)
    b_pub = b.serialize_public_key(b.dh_public_key)
    shared = a.dh_private_key.exchange(b.dh_public_key)
    assert a.compute_shared_secret(b_pub) and b.compute_shared_secret(a_pub)
    assert a.session_key == b.session_key
    session_msg = b.encrypt(message)
    hmac_key = a.derive_key_from_session(a.session_key, b"hmac")

    a_numbers = a.dh_private_key.private_numbers()
    x = a_numbers.x.to_bytes(256, "big")
    y = a_numbers.public_numbers.y.to_bytes(256, "big")
    b_x = b.dh_private_key.private_numbers().x.to_bytes(256, "big")

    # The PEM a current Python station sends, for our encoder to match.
    sys.stdout = quiet
    emit("// Generated by tests/interop/make_vectors.py from the Python version's")
    emit("// CryptoManager.  Do not edit.")
    emit("#pragma once")
    emit("namespace vectors {")
    emit("static const char kPassword[] = %s;" % c_text(password))
    emit("static const char kMessage[] = %s;" % c_text(message))
    emit("static const char kSalt[] = %s;" % c_string(salt))
    emit("static const char kKeyEncryption[] = %s;" % c_string(k_enc))
    emit("static const char kKeyHmac[] = %s;" % c_string(k_mac))
    emit("static const char kPasswordMessage[] = %s;" % c_text(password_msg))
    emit("static const char kStationAPrivateX[] = %s;" % c_string(x))
    emit("static const char kStationAPublicY[] = %s;" % c_string(y))
    emit("static const char kStationAPublicKey[] = %s;" % c_text(a_pub))
    emit("static const char kStationBPublicKey[] = %s;" % c_text(b_pub))
    emit("static const char kStationBPrivateX[] = %s;" % c_string(b_x))
    emit("static const char kSharedSecret[] = %s;" % c_string(shared))
    emit("static const char kSessionKey[] = %s;" % c_string(a.session_key))
    emit("static const char kSessionHmacKey[] = %s;" % c_string(hmac_key))
    emit("static const char kSessionMessage[] = %s;" % c_text(session_msg))
    emit("}  // namespace vectors")
    print("\n".join(out))


if __name__ == "__main__":
    main()
